function counts = readCounts(filename)
%READCOUNTS Parse PANGAEA.980059, keeping Python-compatible species names.
[~, data] = hodor.internal.readTab(string(filename), "SeqID");
species = ["anguilla_anguilla", "bird_cormorant", "bird_unspecified", ...
    "crab_crustacea", "fish_clupeidae", "fish_cod", "fish_mackerel", ...
    "fish_mugilidae", "fish_oncorhynchus", "fish_pipefish", ...
    "fish_plaice", "fish_salmonidae", "fish_scad", "fish_unspecified", ...
    "jellyfish_aurelia", "jellyfish_ctenophora", "jellyfish_cyanea", ...
    "jellyfish_unspecified"];
if size(data, 2) ~= 5+numel(species)
    error('hodor:InvalidMetadata', 'PANGAEA activity counts column layout changed.');
end
counts = table(str2double(data(:,1)), str2double(data(:,2)), ...
    str2double(data(:,3)), 'VariableNames', ...
    {'SeqID','sequenceStartUnix','sequenceEndUnix'});
counts.DateTimeStart = datetime(data(:,4), 'InputFormat', ...
    "yyyy-MM-dd'T'HH:mm:ss.SSS", 'TimeZone', 'UTC');
counts.DateTimeEnd = datetime(data(:,5), 'InputFormat', ...
    "yyyy-MM-dd'T'HH:mm:ss.SSS", 'TimeZone', 'UTC');
counts.sequence_length = counts.DateTimeEnd - counts.DateTimeStart;
for i = 1:numel(species)
    counts.(species(i)) = str2double(data(:,5+i));
end
if any(~isfinite(counts.SeqID)) || numel(unique(counts.SeqID)) ~= height(counts)
    error('hodor:InvalidMetadata', 'Invalid activity-count sequence IDs.');
end
end
